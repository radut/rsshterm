import Foundation

/// Where a third-party component ships. The App Store builds are `.ios` and `.macos`; `.linux` is the desktop app.
public enum ThirdPartyPlatform: String, Sendable, CaseIterable {
    case ios, macos, linux

    /// The platform this binary was built for.
    public static var current: ThirdPartyPlatform {
        #if os(iOS)
        .ios
        #elseif os(macOS)
        .macos
        #else
        .linux
        #endif
    }
}

/// One licence or NOTICE text, shared by every component that ships the same text.
public struct LicenceText: Sendable, Hashable {
    public let title: String
    public let body: String
}

/// A library, font, toolchain part or colour theme the apps include, with what its licence asks us to show.
public struct ThirdPartyComponent: Sendable, Hashable, Identifiable {
    public enum Kind: String, Sendable { case library, font, toolchain, theme }

    public let id: String
    public let name: String
    public let version: String
    /// SPDX expression, e.g. "Apache-2.0" or "MIT AND Bitstream-Vera".
    public let license: String
    public let url: String
    public let kind: Kind
    public let platforms: Set<ThirdPartyPlatform>
    /// A sentence the licence requires in the documentation (CryptoSwift), or a glyph-set attribution.
    public let acknowledgement: String
    /// What the rSshTerm authors changed (vendored, patched copies); empty when unmodified.
    public let changes: String
    /// Keys into `ThirdPartyNotices.texts`.
    let texts: [String]

    init(id: String, name: String, version: String, license: String, url: String, kind: Kind,
         platforms: Set<ThirdPartyPlatform>, acknowledgement: String, changes: String, texts: [String]) {
        self.id = id
        self.name = name
        self.version = version
        self.license = license
        self.url = url
        self.kind = kind
        self.platforms = platforms
        self.acknowledgement = acknowledgement
        self.changes = changes
        self.texts = texts
    }

    /// "Name 1.2.3".
    public var title: String { version.isEmpty ? name : "\(name) \(version)" }
}

/// The third-party notices every app shows (Acknowledgements on iPhone, iPad and Mac; About › Legal on Linux). The
/// data is generated by packaging/licenses/generate.py from packaging/licenses/manifest.toml, which CI checks against
/// the resolved packages, vendored code, fonts and themes.
public enum ThirdPartyNotices {
    /// Every component, sorted by name; themes last.
    public static var all: [ThirdPartyComponent] { generatedComponents }

    /// The components that ship on `platform`.
    public static func components(for platform: ThirdPartyPlatform = .current) -> [ThirdPartyComponent] {
        generatedComponents.filter { $0.platforms.contains(platform) }
    }

    /// The components of one kind that ship on `platform`.
    public static func components(_ kind: ThirdPartyComponent.Kind,
                                  for platform: ThirdPartyPlatform = .current) -> [ThirdPartyComponent] {
        components(for: platform).filter { $0.kind == kind }
    }

    /// The licence and NOTICE texts of a component, in order.
    public static func texts(of component: ThirdPartyComponent) -> [LicenceText] {
        component.texts.compactMap { generatedTexts[$0] }
    }

    /// Everything a licence asks to show for one component: header lines, then the full texts.
    public static func fullNotice(of component: ThirdPartyComponent) -> String {
        var parts = [component.title, "Licence: \(component.license)"]
        if !component.url.isEmpty { parts.append(component.url) }
        if !component.changes.isEmpty { parts.append(component.changes) }
        if !component.acknowledgement.isEmpty { parts.append(component.acknowledgement) }
        let header = parts.joined(separator: "\n")
        let bodies = texts(of: component).map(\.body)
        return ([header] + bodies).joined(separator: "\n\n")
    }

    /// The acknowledgement sentences licences require "in the product documentation", for the top of a credits page.
    public static func requiredAcknowledgements(for platform: ThirdPartyPlatform = .current) -> [String] {
        components(.library, for: platform).map(\.acknowledgement).filter { !$0.isEmpty }
    }
}
