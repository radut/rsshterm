import Foundation

/// The themes in Settings › Terminal › Themes. Values are the palettes as their authors publish them.
public enum TerminalColorSchemes {
    public static let defaultDark = TerminalColorScheme(
        id: "default-dark", name: "Default Dark", isDark: true,
        background: "#000000", foreground: "#D8DEE6", cursor: "#7FB4FF", selection: "#2D3A4D",
        ansi: ["#1B1F24", "#E5534B", "#57AB5A", "#C69026", "#539BF5", "#B083F0", "#39C5CF", "#ADBAC7",
               "#545D68", "#FF938A", "#6BC46D", "#DAAA3F", "#6CB6FF", "#DCBDFB", "#56D4DD", "#EDF1F5"],
        source: "rSshTerm")

    public static let defaultLight = TerminalColorScheme(
        id: "default-light", name: "Default Light", isDark: false,
        background: "#FAFBFC", foreground: "#24292F", cursor: "#0969DA", selection: "#C8DCF5",
        ansi: ["#24292F", "#CF222E", "#116329", "#7D4E00", "#0969DA", "#8250DF", "#1B7C83", "#6E7781",
               "#57606A", "#A40E26", "#1A7F37", "#633C01", "#218BFF", "#A475F9", "#3192AA", "#8C959F"],
        source: "rSshTerm")

    /// Every theme: the two defaults, then the community themes in name order (TerminalColorSchemes+Catalog.swift,
    /// generated by packaging/themes/generate.py from the upstream files).
    public static let all: [TerminalColorScheme] = [defaultDark, defaultLight] + community

    public static var dark: [TerminalColorScheme] { all.filter(\.isDark) }
    public static var light: [TerminalColorScheme] { all.filter { !$0.isDark } }

    /// The pickers' "Popular" section: the defaults, then the most used themes, most used first.
    public static let popular: [TerminalColorScheme] = [defaultDark, defaultLight] + popularIDs.compactMap(scheme(id:))

    /// The pickers' "All" section: every theme, A–Z.
    public static let alphabetical: [TerminalColorScheme] = all.sorted {
        $0.name.localizedStandardCompare($1.name) == .orderedAscending
    }

    private static let byID: [String: TerminalColorScheme] = Dictionary(all.map { ($0.id, $0) }) { first, _ in first }

    public static func scheme(id: String) -> TerminalColorScheme? { byID[id] }

    /// The search field: themes whose name contains every word of `query` (case and accent blind), in `list` order.
    /// An empty query returns `list`.
    public static func matching(_ query: String, in list: [TerminalColorScheme] = alphabetical) -> [TerminalColorScheme] {
        let words = query.split(whereSeparator: \.isWhitespace).map(String.init)
        guard !words.isEmpty else { return list }
        return list.filter { scheme in
            words.allSatisfy { scheme.name.range(of: $0, options: [.caseInsensitive, .diacriticInsensitive]) != nil }
        }
    }
}
